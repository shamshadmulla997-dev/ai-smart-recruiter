package ai_smart_recruiter.service;

import ai_smart_recruiter.model.Resume;
import com.itextpdf.io.font.constants.StandardFonts;
import com.itextpdf.kernel.colors.ColorConstants;
import com.itextpdf.kernel.font.PdfFont;
import com.itextpdf.kernel.font.PdfFontFactory;
import com.itextpdf.kernel.pdf.PdfDocument;
import com.itextpdf.kernel.pdf.PdfWriter;
import com.itextpdf.layout.Document;
import com.itextpdf.layout.element.Paragraph;
import com.itextpdf.layout.properties.TextAlignment;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.util.List;
import java.util.Map;

@Service
public class PdfReportService {

    public byte[] generateCareerReport(Resume resume,
                                       List<String> resumeSkills,
                                       List<Map<String, Object>> topRoles) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {

            PdfWriter writer = new PdfWriter(out);
            PdfDocument pdfDoc = new PdfDocument(writer);
            Document doc = new Document(pdfDoc);

            PdfFont bold = PdfFontFactory.createFont(StandardFonts.HELVETICA_BOLD);
            PdfFont regular = PdfFontFactory.createFont(StandardFonts.HELVETICA);

            // Title
            doc.add(new Paragraph("AI Smart Recruiter")
                    .setFont(bold).setFontSize(22)
                    .setTextAlignment(TextAlignment.CENTER)
                    .setFontColor(ColorConstants.DARK_GRAY));

            doc.add(new Paragraph("Career Guide Report")
                    .setFont(regular).setFontSize(14)
                    .setTextAlignment(TextAlignment.CENTER)
                    .setMarginBottom(20));

            // Candidate
            doc.add(new Paragraph("Candidate Profile").setFont(bold).setFontSize(16));
            doc.add(new Paragraph("Name: " + resume.getCandidateName()).setFont(regular));
            doc.add(new Paragraph("Email: " + resume.getEmail()).setFont(regular));

            if (resume.getPhone() != null) {
                doc.add(new Paragraph("Phone: " + resume.getPhone()).setFont(regular));
            }
            if (resume.getExperienceYears() != null) {
                doc.add(new Paragraph("Experience: " + resume.getExperienceYears() + " years").setFont(regular));
            }
            doc.add(new Paragraph(" "));

            // Skills (using plain paragraphs instead of iText List)
            doc.add(new Paragraph("Skills Detected").setFont(bold).setFontSize(16));

            if (resumeSkills == null || resumeSkills.isEmpty()) {
                doc.add(new Paragraph("No skills detected.").setFont(regular));
            } else {
                StringBuilder sb = new StringBuilder();
                for (String skill : resumeSkills) {
                    sb.append("• ").append(skill).append("\n");
                }
                doc.add(new Paragraph(sb.toString()).setFont(regular));
            }
            doc.add(new Paragraph(" "));

            // Roles
            doc.add(new Paragraph("Best Matching Roles").setFont(bold).setFontSize(16));

            if (topRoles == null || topRoles.isEmpty()) {
                doc.add(new Paragraph("No role matches available.").setFont(regular));
            } else {
                StringBuilder sb = new StringBuilder();
                for (Map<String, Object> role : topRoles) {
                    sb.append("• ")
                      .append(role.get("role"))
                      .append(" — ").append(role.get("score")).append("% match (")
                      .append(role.get("matched")).append("/")
                      .append(role.get("total")).append(" skills)\n");
                }
                doc.add(new Paragraph(sb.toString()).setFont(regular));
            }

            // Footer
            doc.add(new Paragraph(" "));
            doc.add(new Paragraph("Generated by AI Smart Recruiter & Career Guide")
                    .setFont(regular).setFontSize(10)
                    .setTextAlignment(TextAlignment.CENTER)
                    .setFontColor(ColorConstants.GRAY));

            doc.close();
            return out.toByteArray();

        } catch (Exception e) {
            throw new RuntimeException("Failed to generate PDF: " + e.getMessage(), e);
        }
    }
}